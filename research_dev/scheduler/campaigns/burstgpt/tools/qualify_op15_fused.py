"""WS21: qualify the OP15 (Hexagon HTP) fused attention-projection kernel from rig evidence, fail-closed.

The tool never talks to a phone. It binds three artifacts the rig produced for ONE fused shard set and
writes ``OP15_FUSED_QUALIFICATION.json`` with the planner overrides that turn the kernel on::

    python3 -m research_dev.scheduler.campaigns.burstgpt.tools.qualify_op15_fused \\
        --shard-index OP15_FUSED/FFN_SHARDS.json --model qwen3-14b-q4km-dequant-f16 \\
        --numerics OP15_FUSED/NUMERICS.json \\
        --fused-tokens IDENTITY/fused/TOKENS.json --plain-tokens IDENTITY/plain/TOKENS.json \\
        --fused-server-stderr IDENTITY/fused/llama-server.stderr \\
        --output OP15_FUSED/OP15_FUSED_QUALIFICATION.json

* ``--shard-index``: the OP15 index written by ``native/ffn_shard_gguf.py --fused-layers`` (records with
  ``kernel: attn_proj:fused``). The qualified layers are a subset of its fused layers.
* ``--numerics``: ``native/fused_numerics.py`` run against the OP15 worker on the SAME shard (worker in TCP
  mode through ``adb forward``, ``--backend HTP0``): schema ``s43-fused-numerics-v1``, status PASS,
  worst rel-L2 <= 1e-3, rows {1, 2, 4}, every fused layer called (plain and next).
* ``--fused-tokens`` / ``--plain-tokens``: token ids of the same prompts generated by llama-server with the
  OP15 over FunctionFS, once with ``S41_SERVER_FFN_FUSED_{LAYER,NEXT}_MASK`` set and once without
  (``{"schema": "s43-token-identity-v1", "runs": [{"prompt_sha256": hex, "tokens": [ints]}, ...]}``,
  at least 4 runs, identical ids). ``--fused-server-stderr``: that fused run's server stderr; it must log
  ``S41SERVERFFNFUSED layers=<mask>`` for the shard's fused layers and at least one ``S41SERVERFFNFUSEDCALL``.

Everything is pinned by sha256; any disagreement is a refusal, never a partial pass.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[5]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from research_dev.scheduler.adapters.ffn_shards import FUSED_KERNEL, FfnShardIndex, FfnShardIndexError  # noqa: E402

SCHEMA = "s43-op15-fused-qualification-v1"
TOKENS_SCHEMA = "s43-token-identity-v1"
NUMERICS_SCHEMA = "s43-fused-numerics-v1"
DEVICE = "op15-phone"
_FUSED_LINE = re.compile(r"^S41SERVERFFNFUSED layers=([0-9a-f]{16}) next=([0-9a-f]{16})\s*$", re.M)
_FUSED_CALL = re.compile(r"^S41SERVERFFNFUSEDCALL ", re.M)


class QualificationError(Exception):
    pass


def need(condition: bool, message: str) -> None:
    if not condition:
        raise QualificationError(message)


def file_sha256(path: Path) -> str:
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def read(path: Path) -> dict:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise QualificationError(f"{path}: unreadable JSON ({error})") from error
    need(type(value) is dict, f"{path}: not a JSON object")
    return value


def layers_of(mask: int) -> list[int]:
    return [layer for layer in range(64) if mask >> layer & 1]


def layer_spec(mask: int) -> str:
    """Compact LAYERS spec (``1-3,7``) the planner's ``--qualified-kernel`` accepts."""
    layers = layers_of(mask)
    need(bool(layers), "no layers")
    parts, start, previous = [], layers[0], layers[0]
    for layer in layers[1:] + [None]:
        if layer == previous + 1:
            previous = layer
            continue
        parts.append(str(start) if start == previous else f"{start}-{previous}")
        if layer is not None:
            start = previous = layer
    return ",".join(parts)


def shard_fused_masks(index_path: Path) -> tuple[int, int, dict]:
    try:
        index = FfnShardIndex.load(index_path, "/data/local/tmp/ws21-qualify")
    except FfnShardIndexError as error:
        raise QualificationError(f"shard index: {error}") from error
    fused = [row for row in index.records if row.kernel == FUSED_KERNEL]
    need(bool(fused), "the shard index has no fused record")
    geometry = {(row.fused_n_q, row.fused_n_kv) for row in fused}
    need(len(geometry) == 1, "fused shard records disagree on attention geometry")
    layer_mask = next_mask = 0
    for row in fused:
        need(not row.fused_layer_mask & layer_mask, "fused shard records overlap")
        layer_mask |= row.fused_layer_mask
        next_mask |= row.fused_next_mask
    n_q, n_kv = next(iter(geometry))
    return layer_mask, next_mask, {"parent_sha256": index.parent_sha256, "index_sha256": index.index_sha256,
                                   "n_q": n_q, "n_kv": n_kv,
                                   "shards": [{"session": row.session_hint, "sha256": row.shard_sha256,
                                               "layer_mask": f"{row.layer_mask:016x}",
                                               "fused_layer_mask": f"{row.fused_layer_mask:016x}",
                                               "fused_next_mask": f"{row.fused_next_mask:016x}"} for row in fused]}


def numerics_receipt(path: Path, fused_mask: int, next_mask: int, parent_sha256: str, n_q: int, n_kv: int) -> dict:
    numerics = read(path)
    need(numerics.get("schema") == NUMERICS_SCHEMA and numerics.get("status") == "PASS",
         "numerics did not pass (or wrong schema)")
    need(type(numerics.get("worst_rel_l2")) is float and numerics["worst_rel_l2"] <= 1e-3, "numerics rel-L2 above 1e-3")
    need({1, 2, 4} <= set(numerics.get("rows", ())), "numerics must cover rows 1, 2 and 4")
    called = sum(1 << layer for layer in numerics.get("layers", ()))
    called_next = sum(1 << layer for layer in numerics.get("next_layers", ()))
    need(called == fused_mask and called_next == next_mask, "numerics covered other layers than the shard's fused ones")
    hello = numerics.get("fused_hello", {})
    need(int(hello.get("fused_layer_mask", "0"), 16) & fused_mask == fused_mask
         and hello.get("n_q") == n_q and hello.get("n_kv") == n_kv,
         "numerics worker offered another fused mask or geometry")
    expected_calls = len(numerics["rows"]) * (len(numerics["layers"]) + len(numerics["next_layers"])) * int(
        numerics.get("repeats", 1) or 1)
    need(numerics.get("calls") == expected_calls and len(numerics.get("cases", ())) == expected_calls,
         "numerics call count does not match its layers x rows")
    need(all(segment["finite"] and segment["rel_l2"] <= 1e-3 for case in numerics["cases"]
             for segment in case["segments"].values()), "a numerics segment is non-finite or above 1e-3")
    return {"path": str(path), "sha256": file_sha256(path), "worst_rel_l2": numerics["worst_rel_l2"],
            "calls": numerics["calls"], "rows": sorted(numerics["rows"]), "io": numerics.get("io"),
            "fused_weight_hash": hello.get("fused_weight_hash"), "proxy": numerics.get("proxy")}


def _tokens(path: Path) -> list[tuple[str, tuple[int, ...]]]:
    value = read(path)
    need(value.get("schema") == TOKENS_SCHEMA and type(value.get("runs")) is list and len(value["runs"]) >= 4,
         f"{path}: token identity file needs schema {TOKENS_SCHEMA} and >= 4 runs")
    runs = []
    for row in value["runs"]:
        need(type(row) is dict and type(row.get("prompt_sha256")) is str and len(row["prompt_sha256"]) == 64
             and type(row.get("tokens")) is list and len(row["tokens"]) >= 16
             and all(type(token) is int and token >= 0 for token in row["tokens"]),
             f"{path}: a run lacks prompt_sha256 or >= 16 token ids")
        runs.append((row["prompt_sha256"], tuple(row["tokens"])))
    need(len({prompt for prompt, _ in runs}) == len(runs), f"{path}: duplicate prompts")
    return runs


def identity_receipt(fused_tokens: Path, plain_tokens: Path, fused_stderr: Path, fused_mask: int, next_mask: int) -> dict:
    fused, plain = _tokens(fused_tokens), _tokens(plain_tokens)
    need([prompt for prompt, _ in fused] == [prompt for prompt, _ in plain], "fused and plain runs used different prompts")
    matches = [a == b for (_, a), (_, b) in zip(fused, plain)]
    need(all(matches), f"token ids differ in {matches.count(False)} of {len(matches)} runs")
    try:
        stderr = fused_stderr.read_text(encoding="utf-8", errors="replace")
    except OSError as error:
        raise QualificationError(f"{fused_stderr}: unreadable ({error})") from error
    lines = _FUSED_LINE.findall(stderr)
    need(len(lines) == 1, "fused server stderr must log exactly one S41SERVERFFNFUSED line")
    need(int(lines[0][0], 16) == fused_mask and int(lines[0][1], 16) == next_mask,
         "the fused server run used other fused masks than the shard")
    calls = len(_FUSED_CALL.findall(stderr))
    need(calls > 0, "the fused server run made no fused calls")
    return {"runs": len(fused), "tokens_each": [len(tokens) for _, tokens in fused], "token_identity": matches,
            "fused_calls_logged": calls,
            "fused_tokens": {"path": str(fused_tokens), "sha256": file_sha256(fused_tokens)},
            "plain_tokens": {"path": str(plain_tokens), "sha256": file_sha256(plain_tokens)},
            "fused_server_stderr": {"path": str(fused_stderr), "sha256": file_sha256(fused_stderr)}}


def qualify(args: argparse.Namespace) -> dict:
    fused_mask, next_mask, shards = shard_fused_masks(Path(args.shard_index))
    numerics = numerics_receipt(Path(args.numerics), fused_mask, next_mask, shards["parent_sha256"],
                                shards["n_q"], shards["n_kv"])
    identity = identity_receipt(Path(args.fused_tokens), Path(args.plain_tokens), Path(args.fused_server_stderr),
                                fused_mask, next_mask)
    spec = layer_spec(fused_mask)
    return {
        "schema": SCHEMA, "status": "PASS", "device_id": DEVICE, "model_id": args.model, "kernel": FUSED_KERNEL,
        "fused_layer_mask": f"{fused_mask:016x}", "fused_next_mask": f"{next_mask:016x}", "qualified_layers": spec,
        "shards": shards, "numerics": numerics, "token_identity": identity,
        "planner_overrides": [f"--kernels {DEVICE}=ffn,{FUSED_KERNEL}",
                              f"--qualified-kernel {DEVICE}:{args.model}:{FUSED_KERNEL}={spec}"],
        "note": "latency/energy of the fused OP15 call are NOT qualified here; the planner prices them from "
                "measured S41SERVERFFNFUSEDSHAPE lines of the fused server run",
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--shard-index", required=True)
    parser.add_argument("--model", required=True, help="model id the shard set serves")
    parser.add_argument("--numerics", required=True)
    parser.add_argument("--fused-tokens", required=True)
    parser.add_argument("--plain-tokens", required=True)
    parser.add_argument("--fused-server-stderr", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args(argv)
    output = Path(args.output)
    if output.exists():
        print(f"qualify_op15_fused: {output} exists", file=sys.stderr)
        return 1
    try:
        receipt = qualify(args)
    except QualificationError as error:
        print(f"qualify_op15_fused: REFUSED: {error}", file=sys.stderr)
        return 1
    output.write_text(json.dumps(receipt, indent=1, sort_keys=True) + "\n", encoding="ascii")
    print(f"PASS {receipt['device_id']} {receipt['model_id']} {receipt['kernel']} layers {receipt['qualified_layers']}")
    for line in receipt["planner_overrides"]:
        print("  " + line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
