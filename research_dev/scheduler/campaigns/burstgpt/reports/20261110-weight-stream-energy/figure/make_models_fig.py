#!/usr/bin/env python3
"""Write fig-device-energy-models-body.tex: the paper's Figure 1(a), one thin bar per model in each device row
plus a usable-memory panel. Numbers come from ../tables/SUMMARY.json (per-model J/GB; a CPU bar is omitted when
every run of that model sat in the CPU cache). The paper copy is this file with \\xbfigw replaced by \\columnwidth.

    make_models_fig.py [--server] [--no-gpu]
        default     five rows, the paper's figure: testbed desktop CPU and GPU, three phones
        --server    seven rows: adds the workstation (FCHLLX01) CPU and GPU (tried in the paper on 2026-11-13, reverted)
        --no-gpu    drops the GPU rows (the four-row figure of 2026-11-11)
Ratio labels compare each device's fit with the first row (the testbed desktop CPU).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
S = json.loads((HERE.parent / "tables" / "SUMMARY.json").read_text())["devices"]
MODELS = ["qwen25-05b", "qwen3-06b", "llama32-1b", "qwen3-17b", "gemma4-e2b", "qwen3-4b", "qwen3-8b", "gemma4-12b",
          "qwen3-14b", "qwen3-32b"]
PHONE = r"\enspace\textcolor{xbPhoneText}{\textbf{%s$\times$ less}}"
PLAIN = r"\enspace\textcolor{black!60}{%s$\times$ less}"
SERVER = "--server" in sys.argv
ROWS = [  # key in SUMMARY, chip label, sub-label, fill, usable memory GB, ratio-label style (None = no label)
    ("Desktop CPU", "Core i9-12900K", "30 GB/s", "xbDesk", 30, None),
    ("Server CPU", "Threadripper PRO 5995WX", "82 GB/s", "xbDesk", 125, None),
    ("Desktop GPU", "RTX 4060 Ti", "273 GB/s", "xbGPU", 16, PLAIN),
    ("Server GPU", "RTX A6000", "705 GB/s", "xbGPU", 48, PLAIN),
    ("Pixel 10 Pro CPU", "Tensor G5", "27 GB/s", "xbPixel", 11, PHONE),
    ("OnePlus 15 NPU", "Snapdragon 8 Elite Gen 5", "55--72 GB/s", "xbPhone", 10, PHONE),
    ("OnePlus 12 NPU", "Snapdragon 8 Gen 3", "29--45 GB/s", "xbPhone", 6, PHONE),
]
if not SERVER:
    ROWS = [r for r in ROWS if not r[0].startswith("Server")]
if "--no-gpu" in sys.argv:
    ROWS = [r for r in ROWS if not r[0].endswith("GPU")]
REF = S[ROWS[0][0]]["j_per_gb_origin"]
MEM_MAX = max(r[4] for r in ROWS)
MEM_MAX = 32 if MEM_MAX <= 32 else MEM_MAX   # one linear scale for every memory bar
XMAX = 5.9 if SERVER else 5.1                # room for the value label of the longest CPU bar


def short(v):
    """Label number: two significant figures below 10 (8.5, 4.3), integers from 10 up (18, 83)."""
    return f"{v:.0f}" if v >= 9.95 else f"{v:.1f}"


N = len(ROWS)
STEP = 0.072          # y distance between two model bars (row pitch = 1)
PITCH_CM = 3.45 / 4.1  # cm per row unit (the four-row figure was 3.45 cm for 4.1 units)
out = []
w = out.append
w(r"""% Figure 1(a): each device row holds thin bars, one per model from 0.5B (top) to 32B (bottom), and the second
% panel gives the device's usable memory on one linear scale of 0 to MEMMAX GB. Generated by make_models_fig.py
% (report 20261110-weight-stream-energy) from tables/SUMMARY.json; edit the script, not this block.
\begin{tikzpicture}
\pgfplotsset{xbrows/.style={""".replace("MEMMAX", str(MEM_MAX)))
w(f"  scale only axis, height={PITCH_CM * (N + 0.1):.2f}cm, y dir=reverse, hide x axis, ymin=-0.55, ymax={N - 1 + 0.55:.2f},")
w(f"  ytick={{{','.join(str(i) for i in range(N))}}}, axis y line*=left, y axis line style={{draw=black!30}}, major y tick style={{draw=none}},")
w(r"""  clip=false,
}}
\tikzset{val/.style={anchor=west, font=\scriptsize, inner sep=2pt, text=black!85},
         head/.style={anchor=south west, font=\scriptsize\bfseries, inner sep=0pt, text=black!85}}
\begin{axis}[xbrows, name=energy, width=\xbfigw-5.9cm, xmin=0, xmax=XMAX,
  yticklabel style={font=\footnotesize, text=black!85, text width=3.4cm, align=right},""".replace("XMAX", str(XMAX)))
labels = ",\n               ".join(
    "{%s\\\\[-2pt]{\\scriptsize\\color{black!60}%s}}" % (r[1], r[2]) for r in ROWS)
w("  yticklabels={" + labels + "}]")
for i, (key, _, _, fill, _, style) in enumerate(ROWS):
    pm = S[key]["per_model"]
    coords = []
    for m, model in enumerate(MODELS):
        v = pm.get(model)
        if not v or v.get("from_device_fit") or v.get("j_per_gb") is None:
            continue
        y = i + (m - (len(MODELS) - 1) / 2) * STEP
        coords.append(f"({v['j_per_gb']:.3f},{y:.3f})")
    w(f"\\addplot[xbar, bar width=1.35pt, bar shift=0pt, fill={fill}, draw=none] coordinates {{{' '.join(coords)}}};")
    fit = S[key]["j_per_gb_origin"]
    top = max(pm[m]["j_per_gb"] for m in MODELS if m in pm and not pm[m].get("from_device_fit"))
    jtok = short(pm["qwen3-14b"]["j_per_token"])
    ratio = style % (f"{REF / fit:.1f}" if REF / fit < 9.95 else f"{REF / fit:.0f}") if style and i else ""
    w(f"\\node[val] at (axis cs:{top:.3f},{i}) {{{fit:.2f} ({jtok}){ratio}}};")
w(r"""\end{axis}
\node[head] at ([yshift=3pt]energy.north west) {J per GB (J per token)};
% Memory bars share one linear scale of 0 to MEMMAX GB.
\begin{axis}[xbrows, name=fit, at={([xshift=0.25cm]energy.south east)}, anchor=south west,
  width=1.0cm, xmin=0, xmax=MEMMAX, yticklabels={}, y axis line style={draw=none}]""".replace("MEMMAX", str(MEM_MAX)))
for i, (_, _, _, fill, holds, _) in enumerate(ROWS):
    w(f"\\addplot[xbar, bar width=7pt, bar shift=0pt, fill={fill}, draw=none] coordinates {{({holds},{i})}};")
for i, (_, _, _, _, holds, _) in enumerate(ROWS):
    w(f"\\node[val] at (axis cs:{holds},{i}) {{{holds} GB}};")
w(r"""\end{axis}
\node[head] at ([yshift=3pt]fit.north west) {Usable memory};
\end{tikzpicture}%""")
(HERE / "fig-device-energy-models-body.tex").write_text("\n".join(out) + "\n")
print("wrote fig-device-energy-models-body.tex", N, "rows")
